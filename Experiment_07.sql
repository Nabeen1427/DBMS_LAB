-- 3. Equi Join: employee number/name, department and location.
SELECT e.EMPNO, e.ENAME, d.DNAME, d.LOC
FROM EMP e, DEPT d
WHERE e.DEPTNO = d.DEPTNO;

-- 4. Non-Equi Join: match salary to a salary grade range.
SELECT e.EMPNO, e.ENAME, e.SAL, s.GRADE
FROM EMP e
JOIN SALGRADE s ON e.SAL BETWEEN s.LOSAL AND s.HISAL
ORDER BY e.EMPNO;

-- 5. Self-Join: employee and manager names.
SELECT e.ENAME AS EmployeeName, m.ENAME AS ManagerName
FROM EMP e
LEFT JOIN EMP m ON e.MGR = m.EMPNO;

-- 6. Cartesian Join: every employee-department combination.
SELECT e.ENAME, d.DNAME
FROM EMP e CROSS JOIN DEPT d;

-- 7. ANSI SQL joins.
-- INNER JOIN
SELECT e.EMPNO, e.ENAME, d.DNAME
FROM EMP e INNER JOIN DEPT d ON e.DEPTNO = d.DEPTNO;

-- LEFT OUTER JOIN
SELECT d.DNAME, e.ENAME
FROM DEPT d LEFT OUTER JOIN EMP e ON d.DEPTNO = e.DEPTNO;

-- RIGHT OUTER JOIN
SELECT d.DNAME, e.ENAME
FROM EMP e RIGHT OUTER JOIN DEPT d ON e.DEPTNO = d.DEPTNO;

-- FULL OUTER JOIN equivalent in MySQL using UNION.
SELECT d.DEPTNO, d.DNAME, e.EMPNO, e.ENAME
FROM DEPT d LEFT JOIN EMP e ON d.DEPTNO = e.DEPTNO
UNION
SELECT d.DEPTNO, d.DNAME, e.EMPNO, e.ENAME
FROM DEPT d RIGHT JOIN EMP e ON d.DEPTNO = e.DEPTNO;

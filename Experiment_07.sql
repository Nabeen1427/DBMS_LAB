-- EXPERIMENT 7: SQL JOINS
CREATE DATABASE IF NOT EXISTS Experiment7DB;
USE Experiment7DB;

DROP TABLE IF EXISTS EMP;
DROP TABLE IF EXISTS SALGRADE;
DROP TABLE IF EXISTS AREAS;
DROP TABLE IF EXISTS DEPT;

CREATE TABLE DEPT (
    DEPTNO INT PRIMARY KEY,
    DNAME VARCHAR(40) NOT NULL,
    LOC VARCHAR(40)
);

CREATE TABLE AREAS (
    AREA_ID INT PRIMARY KEY,
    AREA_NAME VARCHAR(40) NOT NULL,
    CITY VARCHAR(40)
);

CREATE TABLE SALGRADE (
    GRADE INT PRIMARY KEY,
    LOSAL DECIMAL(10,2) NOT NULL,
    HISAL DECIMAL(10,2) NOT NULL
);

CREATE TABLE EMP (
    EMPNO INT PRIMARY KEY,
    ENAME VARCHAR(40) NOT NULL,
    JOB VARCHAR(30),
    MGR INT NULL,
    HIREDATE DATE,
    SAL DECIMAL(10,2),
    DEPTNO INT,
    AREA_ID INT,
    CONSTRAINT fk_emp_dept FOREIGN KEY (DEPTNO) REFERENCES DEPT(DEPTNO),
    CONSTRAINT fk_emp_area FOREIGN KEY (AREA_ID) REFERENCES AREAS(AREA_ID),
    CONSTRAINT fk_emp_manager FOREIGN KEY (MGR) REFERENCES EMP(EMPNO)
);

